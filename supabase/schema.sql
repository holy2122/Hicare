  on public.hicare_condition_audits (condition_id, changed_at desc);

-- -----------------------------------------------------------------------------
-- Employee activity logs
-- -----------------------------------------------------------------------------

create table if not exists public.hicare_activity_logs (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  event_type varchar(64) not null check (event_type in ('page_visit', 'condition_open', 'guide_open')),
  condition_id varchar(64),
  keyword_id varchar(128),
  metadata jsonb,
  created_at timestamptz not null default now()
