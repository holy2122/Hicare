-- Optional convenience view for Admin dashboards. RLS on the base tables still
-- applies to the view when queried by authenticated users.
create or replace view public.hicare_activity_report
with (security_invoker = true)
as
select
  l.id,
  l.user_id,
  u.name,
  u.email,
  l.event_type,
  l.condition_id,
  l.keyword_id,
  l.metadata,
  l.created_at
from public.hicare_activity_logs l
left join public.users u on u.id = l.user_id;

grant select on public.hicare_activity_report to authenticated;
