-- Hi Care Supabase schema
-- PostgreSQL / Supabase
--
-- This schema mirrors the current Hi Care application tables:
--   users
--   hicare_admin_accounts
--   hicare_condition_statuses
--   hicare_condition_audits
--   hicare_activity_logs
--
-- Authentication note:
-- The current application uses its own email/password session cookie. The
-- auth_user_id column is included so the database can be migrated to Supabase
-- Auth without losing the existing member records. Once Supabase Auth is used,
-- set users.auth_user_id = auth.users.id for each member. The Supabase
-- service_role key bypasses RLS and must only be used on the server.

create extension if not exists pgcrypto;

-- -----------------------------------------------------------------------------
-- Shared trigger helper
-- -----------------------------------------------------------------------------

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- -----------------------------------------------------------------------------
-- Members
-- -----------------------------------------------------------------------------

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  -- Existing Hi Care local identifier. Example: local_<uuid>.
  open_id varchar(64) not null unique,
  -- Optional future link to Supabase Auth.
  auth_user_id uuid unique references auth.users(id) on delete set null,
  name text,
  email varchar(320),
  login_method varchar(64) default 'local',
  -- Current application stores scrypt output as 128 hex characters and the
  -- random salt as 32 hex characters. Keep both nullable for Supabase Auth rows.
  password_hash varchar(128),
  password_salt varchar(32),
  role text not null default 'user' check (role in ('user', 'admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_signed_in timestamptz not null default now(),
  constraint users_local_credentials_check check (
    (login_method = 'local' and password_hash is not null and password_salt is not null)
    or login_method is distinct from 'local'
    or (password_hash is null and password_salt is null)
  )
);

create unique index if not exists users_email_lower_unique
  on public.users (lower(email))
  where email is not null;

create index if not exists users_created_at_idx on public.users (created_at desc);
create index if not exists users_last_signed_in_idx on public.users (last_signed_in desc);

 drop trigger if exists users_set_updated_at on public.users;
create trigger users_set_updated_at
before update on public.users
for each row execute function public.set_updated_at();

-- -----------------------------------------------------------------------------
